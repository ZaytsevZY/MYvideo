// Additive camera integration. Keeps the previous whole-motion preview bundle intact.
import fs from 'node:fs';
import path from 'node:path';
import crypto from 'node:crypto';
import {fileURLToPath} from 'node:url';
import {CAMERA_BEATS,CAMERA_LAYOUT,sampleCameraScene,cameraDefinitions,drawCameraScene} from './camera-motion.mjs';
import {rootSvg} from '../../characters/rigs/runtime/rig.mjs';
const DIR=path.dirname(fileURLToPath(import.meta.url)),ROOT=path.resolve(DIR,'../../..');
const read=p=>fs.readFileSync(path.resolve(ROOT,p));
const json=p=>JSON.parse(read(p));
const sha=p=>crypto.createHash('sha256').update(read(p)).digest('hex');
const relative=p=>path.relative(DIR,path.resolve(ROOT,p)).split(path.sep).join('/');
const bundle={version:'S01_CAMERA_PREVIEW v0.1',script:'S01_CAMERA v0.2',poses:{},assets:{},layout:CAMERA_LAYOUT,diagramPanels:json('arts/static/01/diagram-panels-v01.json')};
for(const a of json('arts/characters/poses/01/manifest-v02.json').assets)bundle.poses[a.id]={dataUri:relative(a.path),path:a.path,width:a.size[0],height:a.size[1]};
for(const a of json('arts/static/01/camera-assets-manifest-v01.json').assets){
 const item={dataUri:relative(a.path),path:a.path,width:a.size[0],height:a.size[1]};
 if(['N1','N2','N3'].includes(a.id))bundle.poses[a.key]=item;
 else bundle.assets[a.id==='N4'?'room-reverse-night':'monitor-back']=item;
}
for(const tone of ['night','day']){
 const p='arts/backgrounds/01/workroom-'+tone+'-v01.png';bundle.assets['room-'+tone]={dataUri:relative(p),path:p,width:1672,height:941};
}
for(const a of json('arts/static/01/native-assets-v01.json')){
 if(a.id==='logic-panel')continue;
 bundle.assets[a.id]={dataUri:relative(a.path),path:a.path,width:a.size[0],height:a.size[1]};
}
bundle.assets['chair-back-rear']={dataUri:relative('arts/items/01/chair-back-rear-v02.svg'),path:'arts/items/01/chair-back-rear-v02.svg',width:340,height:480};
fs.writeFileSync(path.join(DIR,'bundle-camera-v01.json'),JSON.stringify(bundle));
fs.writeFileSync(path.join(DIR,'layout-camera-v01.json'),JSON.stringify(CAMERA_LAYOUT,null,2)+'\n');
const samples=[];
for(let frame=0;frame<=1350;frame++)samples.push({frame,...sampleCameraScene(frame/30)});
fs.writeFileSync(path.join(DIR,'scene-camera-30fps-v01.json'),JSON.stringify({version:bundle.version,kind:'deterministic scene state; not raster animation frames',fps:30,durationSeconds:45,frames:samples}));
const inline=(item)=>({...item,dataUri:'data:'+(item.path.endsWith('.svg')?'image/svg+xml':'image/png')+';base64,'+read(item.path).toString('base64')});
const stillDIR=path.join(DIR,'camera-stills');fs.mkdirSync(stillDIR,{recursive:true});
const stills=[];
for(const beat of CAMERA_BEATS){
 const t=(beat.start+beat.end)/2,state=sampleCameraScene(t),content=drawCameraScene(state,bundle);
 const ids=prefix=>[...new Set([...content.matchAll(new RegExp('href="#'+prefix+'-([^"#]+)"','g'))].map(m=>m[1]))];
 const assets={},poses={};
 for(const id of ids('asset')){if(!bundle.assets[id])throw Error('Missing asset '+id);assets[id]=inline(bundle.assets[id]);}
 for(const id of ids('pose')){if(!bundle.poses[id])throw Error('Missing pose '+id);poses[id]=inline(bundle.poses[id]);}
 const active={...bundle,assets,poses};
 const p='arts/actions/01/camera-stills/'+beat.id+'-v01.svg';
 fs.writeFileSync(path.resolve(ROOT,p),rootSvg(content,cameraDefinitions(active),1920,1080,beat.id+' '+beat.name));
 stills.push({id:beat.id,t,path:p,sha256:sha(p)});
}
const inputs=[...Object.values(bundle.poses),...Object.values(bundle.assets)].map(a=>({path:a.path,sha256:sha(a.path)}));
const manifest={version:bundle.version,script:bundle.script,codeAuthor:'camera-motion initial module generated by Claude Opus 5.5; integration and reviewed edits by Codex',poses:Object.keys(bundle.poses).length,newAssetIds:['N1','N2','N3','N4','N5'],beats:CAMERA_BEATS,samples:samples.length,sampleFps:30,rasterAnimationFrames:0,mp4:false,audio:false,remotionProject:false,oldPreview:'whole-motion.mjs and bundle-whole-v01.json preserved',bundleMode:'relative source URLs for browser cache; key still SVGs embed only referenced art',stills,inputs,code:['arts/actions/01/camera-motion.mjs','arts/actions/01/bake-camera.mjs','arts/actions/01/preview.html'].map(p=>({path:p,sha256:sha(p)})),limitations:['provisional timing; no recorded narration','finite complete drawings, no anatomical inbetweening','state sampling at30fps is not newly drawn30fps cels','next-chapter handoff visual only; chapter02 not implemented here']};
fs.writeFileSync(path.join(DIR,'manifest-camera-v01.json'),JSON.stringify(manifest,null,2)+'\n');
console.log(JSON.stringify({version:bundle.version,beats:CAMERA_BEATS.length,poses:Object.keys(bundle.poses).length,samples:samples.length,stills:stills.length,bundleBytes:fs.statSync(path.join(DIR,'bundle-camera-v01.json')).size}));
